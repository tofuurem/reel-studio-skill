#!/usr/bin/env python3
"""The whole dialogue of a reel as ONE processed stem → reel/public/audio/dialogue.wav (48 kHz mono 24-bit, timeline time),
reel/src/dialogueSrc.ts (DIALOGUE = its path: Clip.tsx then mutes the proxies' own sound, Dialogue.tsx plays the stem) and
work/voice/dialogue.json (what was done, for audio_qa.py and doctor.py).

Usage: work/dfvenv/bin/python -I dialogue.py <project> [--cutlist work/cutlist.json] [--voice-dir work/voice/out]
                                            [--bleeps work/bleeps.json | --no-bleeps] [--tune work/voice_tune.json]
                                            [--keep-raw] [--force]
Run after gen_timeline.py (any cut-list change → re-run; doctor.py says when it is stale). Prints DIALOGUE_DONE.

Why (2026-11-07 audit of the reel-studio reel): the voice reached the render as per-clip AAC proxies switched hard on every
cut, levelled by three compressors in a row and encoded four times. Here, from the restored voice of voice_clean.py (float,
never encoded):
1. Assembly, sample-accurate on the cut list's frames: every main-track segment's source range is placed at its timeline
   position; a jump cut gets an equal-power crossfade of cutXfadeMs taken from the source handles (no click, no gap), two
   segments continuing one take a joinXfadeMs linear join; speed changes are time-stretched like Remotion does (atempo);
   CapCut voiceovers land where the draft put them.
2. Levels: each take's active speech to voiceTargetDb (≤ voiceMaxGain up), each segment nudged into [voiceSegLo,
   voiceSegHi] (± voiceSegMax); "amb" segments add the camera's own sound at ambDb kept out from under every word, "raw"
   ones use the camera sound at rawDb instead of the cleaned voice (plan.json opts; see event-vlog.md). A picture beat
   with no word in its source range (Halloween v4: an Action 5 Pro on the handlebar, wind only, no transcript) needs no
   restored voice: it is the camera sound at ambDb over room tone (its "voice" was the wind at full level).
3. Room tone: gaps and muted slivers are filled with the quietest stretch of the neighbouring take (looped) — never
   digital silence between words.
4. ONE chain over the whole stem (voicelib.voice_chain): high-pass → measured mud/box cuts → one soft-knee compressor →
   measured presence/air → de-esser → static gain to stemLufs → look-ahead peak limiter at stemPeakDb.
5. Bleeps (work/bleeps.json, timeline ms) go into the stem: the word muted, the soft boop in its place — bleep.py on the
   render is then not needed (it would re-encode the sound once more).
6. Sound bridges (J/L cuts) on scene changes — `--bridge` for every cut between two different takes, or "bridge": true on
   a plan range for that cut: the outgoing scene's own camera sound carries bridgeTail s under the next picture (L) and
   the incoming one starts bridgeLead s before its picture (J), both at ambDb, faded, kept out from under every word —
   the place changes before or after the picture does, so the cut feels like one event (event-vlog.md).
7. A picture beat sped up ambRealtimeSpeed× or more (a ride as a time-lapse) plays its camera sound in REAL time from the
   beat's first second — the wind and the engine as they were; time-stretched ×15 it was a grinding texture (Halloween v5).
8. Digital zeros inside a take (a radio-mic dropout in the source, the edge of a cleaned voice window) longer than
   dropoutMs count as a hole: the room tone fills it like a gap (c0081: 0.5 s of zeros read as a broken frame); the
   camera sound under a picture beat or a bridge fills its own dropouts from the stretch just before (patch_dropouts).
9. Optional per-project voice decisions, work/voice_tune.json (no file = everything below OFF, the stem as before):
   {"leveler": true | {"amount", "max_db"}}  a slow leveler over the placed speech (before room tone, not on amb/raw/bridges)
   for a voice that wanders inside a take (distance to the mic); {"expander": true | {...}, "notches": "auto" | "<eq>",
   "extraEq": "<eq>", "hpf": "<high-pass>"} go into voice_chain. Decide them with voice_probe.py → eq_test.py → ab.py on a
   short stretch, never by rebuilding the whole reel (craft/ab.md).
--keep-raw also writes work/voice/dialogue_raw.wav (steps 1–3 only) for an A/B by ear.
"""
import argparse, hashlib, json, os, sys
import numpy as np, soundfile as sf
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import N, add_guard_args, clip_id, guard_reexec, load_json, speech_tracks
import voicelib as V

SR = V.SR
VERSION = 5   # 3: picture beats without words play the camera sound at ambDb over room tone (2 left holes); 4: J/L bridges;
              # 5: sped-up picture beats sound in real time, digital zeros inside a take (lav dropouts) get room tone
TS = """/** Generated by scripts/dialogue.py — the processed dialogue stem (one file for the whole reel, timeline time).
 *  When set, Clip mutes the proxies' own sound and <Dialogue /> plays this instead; null = the proxies carry the voice. */
export const DIALOGUE: string | null = {val};
"""


def flag(s, k):
    return bool(s.get(k) or (s.get("meta") or {}).get(k))


class Sources:
    """Restored voice per clip id (float WAV, source time) with zero padding outside the file."""
    def __init__(self, vdir):
        self.vdir = vdir; self.cache = {}

    def path(self, it):
        for c in (it["base"], it["cid"]):   # an alias clip (cut_from_transcript <id>x<k>) is the same take
            p = os.path.join(self.vdir, f"{c}_DeepFilterNet3.wav")
            if os.path.exists(p): return p
        return None

    def get(self, it, a, b, camera=False):
        """Samples of source seconds [a, b) of the item's voice (camera=True: the camera's own track)."""
        n = int(round((b - a) * SR)); out = np.zeros(n)
        if camera or not self.path(it):
            src = os.path.realpath(it["path"]); key = ("cam", src)
            if key not in self.cache:
                x = V.read(src); self.cache[key] = x
            x = self.cache[key]; i0 = int(round(a * SR))
            lo, hi = max(0, i0), min(len(x), i0 + n)
            if hi > lo: out[lo - i0: hi - i0] = x[lo:hi]
            return out
        p = self.path(it); info = sf.info(p); i0 = int(round(a * SR))
        lo, hi = max(0, i0), min(info.frames, i0 + n)
        if hi > lo: out[lo - i0: hi - i0] = sf.read(p, start=lo, stop=hi, dtype="float64", always_2d=False)[0]
        return out


def stretch(x, speed, n):
    """Time-stretch by `speed` (pitch kept, like Remotion's playbackRate) to exactly n samples."""
    if abs(speed - 1) < 1e-3: return V.fit(x, n)
    f, chain = speed, []
    while f > 2.0: chain.append("atempo=2.0"); f /= 2.0
    while f < 0.5: chain.append("atempo=0.5"); f /= 0.5
    chain.append(f"atempo={f:.6f}")
    return V.fit(V.ffilter(x, ",".join(chain)), n)


def alive(x):
    """1 where the signal is live, 0 inside runs of digital zeros longer than dropoutMs (10 ms ramps at the edges)."""
    z = np.abs(x) < 1e-6; n = len(x); m = np.ones(n)
    if not z.any(): return m
    idx = np.flatnonzero(np.diff(np.concatenate([[0], z.astype(np.int8), [0]])))
    k = int(N["dropoutMs"] / 1000 * SR); R = int(0.01 * SR)
    for r0, r1 in zip(idx[::2], idx[1::2]):
        if r1 - r0 < k: continue
        m[r0:r1] = 0
        a = max(0, r0 - R); m[a:r0] = np.minimum(m[a:r0], np.linspace(1, 0, r0 - a))
        b = min(n, r1 + R); m[r1:b] = np.minimum(m[r1:b], np.linspace(0, 1, b - r1))
    return m


def patch_dropouts(x):
    """The camera's own sound with its dropouts (digital zeros > dropoutMs) filled from the stretch right before them
    (after them at the very start), 10 ms crossfades — a picture beat's ambience must not dip into the room tone."""
    m = alive(x)
    if m.min() > 0.5: return x
    y = x.copy(); z = m < 0.5; idx = np.flatnonzero(np.diff(np.concatenate([[0], z.astype(np.int8), [0]])))
    for r0, r1 in zip(idx[::2], idx[1::2]):
        n = r1 - r0; src = x[r0 - n: r0] if r0 >= n else x[r1: r1 + n]
        if len(src) != n: continue
        k = min(n // 2, int(0.01 * SR)); env = np.ones(n)
        if k: env[:k] = np.linspace(0, 1, k); env[-k:] = np.linspace(1, 0, k)
        y[r0:r1] = src * env
    return y


def fade(n, kind):
    t = np.linspace(0, 1, n) if n > 1 else np.ones(max(n, 0))
    return np.sin(t * np.pi / 2) if kind == "power" else t


def words_of(cl, s, aliases):
    wm = cl.get("words") or {}; cid = clip_id(s["path"])
    f = wm.get(s.get("clip", "")) or wm.get(aliases.get(cid, cid)[1:])
    return [w for sg in json.load(open(f))["segments"] for w in sg.get("words", [])] if f and os.path.exists(f) else []


def speech_gate(words, a, n):
    """1 where nobody speaks, 0 under every word (±0.25 s), 0.12 s ramps — n samples from source second a."""
    g = np.ones(n); R = int(0.12 * SR)
    for w in words:
        i0 = int((w["start"] - 0.25 - a) * SR); i1 = int((min(w["end"], w["start"] + 0.9) + 0.25 - a) * SR)
        if i1 < 0 or i0 > n: continue
        g[max(0, i0): min(n, i1)] = 0
    c = np.concatenate([[0.0], np.cumsum(g)]); i = np.arange(n); lo = np.maximum(0, i - R // 2); hi = np.minimum(n, i + R // 2 + 1)
    return (c[hi] - c[lo]) / (hi - lo)


def items_of(cl):
    fps = cl["fps"]; aliases = cl.get("aliases") or {}; out = []
    for s in cl["main"]:
        if s.get("materialType", "video") != "video": continue
        cid = clip_id(s["path"]); vol = float(s.get("volume", 1))
        kind = "mute" if vol < 0.01 else "raw" if flag(s, "raw") else "amb" if flag(s, "amb") else "speech"
        out.append({"kind": kind, "t0": s["fromFrame"] / fps, "d": s["durFrames"] / fps, "s0": float(s["srcStart"]), "speed": float(s.get("speed", 1) or 1),
                    "cid": cid, "base": aliases.get(cid, cid), "path": s["path"], "fadeIn": float(s.get("audioFadeIn") or 0) / fps, "vo": False, "seg": s})
    for sg in speech_tracks(cl):
        cid = clip_id(sg["path"]); s0 = float(sg["srcStart"]) if "srcStart" in sg else sg.get("trimBeforeFrames", 0) / fps
        out.append({"kind": "speech", "t0": sg["fromFrame"] / fps, "d": sg["durFrames"] / fps, "s0": s0, "speed": float(sg.get("speed", 1) or 1),
                    "cid": cid, "base": cid, "path": sg["path"], "fadeIn": 0.0, "vo": True, "seg": sg})
    return out


def edges(items, fps):
    """Per item (left, right) = (seconds, kind): a jump cut → cutXfadeMs equal power; the same take continuing → joinXfadeMs
    linear (sums back to the continuous signal); next to a gap or a muted sliver → a cut fade, room tone fills the rest."""
    cut = (N["cutXfadeMs"] / 1000, "power"); join = (N["joinXfadeMs"] / 1000, "linear")
    main = sorted([it for it in items if not it["vo"]], key=lambda it: it["t0"])
    for it in items: it["L"] = it["R"] = cut; it["cutL"] = False
    for p, q in zip(main, main[1:]):
        if abs(p["t0"] + p["d"] - q["t0"]) > 1.5 / fps or "mute" in (p["kind"], q["kind"]): continue
        same = (p["base"] == q["base"] and p["kind"] == q["kind"] != "amb" and abs(p["speed"] - q["speed"]) < 1e-3
                and abs(p["s0"] + p["d"] * p["speed"] - q["s0"]) < 1.5 / fps)
        p["R"] = q["L"] = join if same else cut; q["cutL"] = not same


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("project")
    ap.add_argument("--cutlist", default="work/cutlist.json"); ap.add_argument("--voice-dir", default="work/voice/out")
    ap.add_argument("--out", default="reel/public/audio/dialogue.wav"); ap.add_argument("--bleeps", default="work/bleeps.json")
    ap.add_argument("--no-bleeps", action="store_true"); ap.add_argument("--tune", default="work/voice_tune.json")
    ap.add_argument("--keep-raw", action="store_true"); ap.add_argument("--force", action="store_true")
    ap.add_argument("--bridge", action="store_true", help="J/L sound bridges on every cut between two different takes (event vlogs)")
    add_guard_args(ap, 10.0)   # whole-timeline float64 arrays at 48 kHz: ≈ 0.4 GB per array per 17 min
    a = ap.parse_args(); guard_reexec(a); P = os.path.abspath(a.project); os.chdir(P)
    cl = load_json(a.cutlist)
    if not cl: sys.exit(f"no cut list at {a.cutlist}")
    ts_path = "reel/src/dialogueSrc.ts"
    if cl.get("silent"):
        if os.path.isdir("reel/src"): open(ts_path, "w").write(TS.format(val="null"))
        print("DIALOGUE_DONE none (silent cut list)"); return
    fps = cl["fps"]; aliases = cl.get("aliases") or {}
    items = items_of(cl); src = Sources(a.voice_dir); edges(items, fps)
    # a picture beat with no word in its source range (an action cam on the handlebar: wind; no transcript at all) has no
    # voice to restore — its "restored voice" would be the wind at full level; it plays the camera's sound at ambDb and the
    # room tone fills under it. A beat WITH words keeps its restored voice: on lav clips the camera track is the same lavs,
    # gated under every word, so dropping the voice left holes (Halloween v4 first render)
    for it in items:
        it["pic"] = False
        if it["kind"] == "amb" and not it["vo"]:
            a0, a1 = it["s0"] - 0.2, it["s0"] + it["d"] * it["speed"] + 0.2
            it["pic"] = not any(a0 <= w["start"] <= a1 for w in words_of(cl, it["seg"], aliases))
    missing = sorted({it["cid"] for it in items if it["kind"] in ("speech", "amb") and not it["vo"] and not it["pic"] and not src.path(it)})
    if missing: sys.exit(f"no restored voice for {', '.join(missing)} in {a.voice_dir} — run voice_clean.py (voice_isolate.sh) / dualmic.py first")
    bleeps = [] if a.no_bleeps else (load_json(a.bleeps, []) or [])
    tune = {k: v for k, v in (load_json(a.tune, {}) or {}).items() if not k.startswith("_")}   # "_why": notes for people
    vfiles = sorted({src.path(it) for it in items if src.path(it)})
    sig = hashlib.md5(json.dumps([VERSION, a.bridge, open(a.cutlist).read(), [(f, os.path.getmtime(f)) for f in vfiles], bleeps,
                                  {k: v for k, v in N.items() if not isinstance(v, (list, dict))}] + ([tune] if tune else [])).encode()).hexdigest()[:12]
    rep_p = "work/voice/dialogue.json"; old = load_json(rep_p, {}) or {}
    if not a.force and old.get("sig") == sig and os.path.exists(a.out):
        os.utime(a.out)   # inputs rewritten with the same content: mark the stem current, or doctor.py (mtime) blocks the render forever
        print("dialogue unchanged"); print("DIALOGUE_DONE", a.out); return

    # ---- 1. pieces with handles, 2. levels
    for it in items:
        if it["kind"] == "mute": continue
        hl, hr = it["L"][0] / 2, it["R"][0] / 2
        a0 = it["s0"] - hl * it["speed"]; a1 = it["s0"] + (it["d"] + hr) * it["speed"]
        n = int(round((it["d"] + hl + hr) * SR))
        x = np.zeros(int(round((a1 - a0) * SR))) if it["pic"] else src.get(it, a0, a1, camera=it["kind"] == "raw")
        it["x"] = stretch(x, it["speed"], n); it["hl"], it["hr"] = hl, hr
    gain = {}
    for b in sorted({it["base"] for it in items if it["kind"] == "speech"}):
        parts = [it["x"][int(it["hl"] * SR): len(it["x"]) - int(it["hr"] * SR)] for it in items if it["base"] == b and it["kind"] == "speech"]
        lv = V.active_db(np.concatenate(parts)) if parts else None
        gain[b] = 0.0 if lv is None else float(np.clip(N["voiceTargetDb"] - lv, -12, N["voiceMaxGain"]))
    for it in items:
        if it["kind"] == "mute": continue
        if it["kind"] == "raw":
            lv = V.active_db(it["x"]); it["g"] = 0.0 if lv is None else N["rawDb"] - lv; continue
        g = gain.get(it["base"], 0.0); it["g"] = g
        if it["kind"] == "speech" and it["d"] >= 1.0:
            lv = V.active_db(it["x"] * 10 ** (g / 20))
            if lv is not None and not (N["voiceSegLo"] <= lv <= N["voiceSegHi"]):
                it["g"] = g + float(np.clip((N["voiceSegLo"] if lv < N["voiceSegLo"] else N["voiceSegHi"]) - lv, -N["voiceSegMax"], N["voiceSegMax"]))

    # ---- placement
    T = max(cl.get("totalFrames", 0) / fps, max(it["t0"] + it["d"] for it in items)) + 0.5
    L = int(T * SR); stem = np.zeros(L); cover = np.zeros(L); cuts = []
    lev = tune.get("leveler")
    side = np.zeros(L) if lev else stem   # leveling: camera sound (amb, raw) stays out of it and is added after
    for it in items:
        if it["kind"] == "mute": continue
        x = it["x"] * 10 ** (it["g"] / 20); n = len(x); env = np.ones(n)
        (lf, lk), (rf, rk) = it["L"], it["R"]
        kl, kr = int(lf * SR), int(rf * SR)
        if kl: env[:kl] *= fade(kl, lk)
        if kr: env[n - kr:] *= fade(kr, rk)[::-1]
        if it["fadeIn"] > lf:   # Clip's audioFadeIn (a cut inside a word): a longer linear ramp from the cut
            k0 = int(it["hl"] * SR); kf = min(n - k0, int(it["fadeIn"] * SR)); env[:k0] = 0; env[k0: k0 + kf] *= np.linspace(0, 1, kf)
        i0 = int(round((it["t0"] - it["hl"]) * SR)); lo, hi = max(0, i0), min(L, i0 + n)
        if not it["pic"]:   # pic: room tone fills it; so it does a dropout (digital zeros) inside the take
            (side if it["kind"] == "raw" else stem)[lo:hi] += (x * env)[lo - i0: hi - i0]; cover[lo:hi] += (env * alive(x))[lo - i0: hi - i0]
        if it["cutL"]: cuts.append(round(it["t0"], 3))
        if it["kind"] == "amb":   # the event's own sound under a picture beat, kept out from under every word
            fast = it["speed"] >= N["ambRealtimeSpeed"]   # a time-lapse: the place in real time, not stretched
            t0s = it["s0"] - 0.2; d = it["d"] * (1 if fast else it["speed"]) + 0.4
            cam = patch_dropouts(src.get(it, t0s, t0s + d, camera=True)); lv = V.active_db(cam)
            if lv is not None:
                cam = cam * 10 ** ((N["ambDb"] - lv) / 20) * speech_gate(words_of(cl, it["seg"], aliases), t0s, len(cam))
                R = int(0.15 * SR); cam[:R] *= np.linspace(0, 1, R); cam[-R:] *= np.linspace(1, 0, R)
                cam = V.fit(cam, int(round((it["d"] + 0.4) * SR))) if fast else stretch(cam, it["speed"], int(round((it["d"] + 0.4) * SR)))
                j0 = int(round((it["t0"] - 0.2) * SR)); lo, hi = max(0, j0), min(L, j0 + len(cam))
                side[lo:hi] += cam[lo - j0: hi - j0]
    levrep = None; rawpre = None
    if lev:   # 9. the slow leveler over the speech only (it holds through pauses, so the gaps do not pump)
        if a.keep_raw: rawpre = stem + side   # dialogue_raw.wav stays un-leveled: eq_test.py tries levelers on it
        lv = lev if isinstance(lev, dict) else {}
        stem, levrep = V.leveler(stem, N["voiceTargetDb"], lv.get("amount", N["levelerAmount"]), lv.get("max_db", N["levelerMaxDb"]))
        stem += side; del side

    def put(lo, hi, y):   # everything after the leveler goes into the stem (and into the un-leveled raw copy)
        stem[lo:hi] += y
        if rawpre is not None: rawpre[lo:hi] += y

    # ---- 6. J/L bridges: the next place is heard a moment before it is seen, the last one lingers under the new picture
    nbr = 0
    main_live = sorted([it for it in items if it["kind"] != "mute" and not it["vo"]], key=lambda it: it["t0"])
    def bridge(it, a0, dur, at, up):
        """The item's camera sound, source seconds [a0, a0 + dur·speed), at ambDb, gated under words, ramped, placed at `at`."""
        if dur <= 0.05: return False
        lvl = V.active_db(src.get(it, it["s0"] - 2, it["s0"] + it["d"] * it["speed"] + 2, camera=True))   # the take's own level
        if lvl is None: return False
        sp = 1.0 if it["speed"] >= N["ambRealtimeSpeed"] else it["speed"]   # a time-lapse bridges in real time too
        cam = patch_dropouts(src.get(it, a0, a0 + dur * sp, camera=True)) * 10 ** ((N["ambDb"] - lvl) / 20)
        cam = cam * speech_gate(words_of(cl, it["seg"], aliases), a0, len(cam))
        cam = stretch(cam, sp, int(round(dur * SR)))
        ramp = np.linspace(0, 1, len(cam)) ** 1.5; cam *= ramp if up else ramp[::-1]
        j0 = int(round(at * SR)); lo, hi = max(0, j0), min(L, j0 + len(cam))
        if hi > lo: put(lo, hi, cam[lo - j0: hi - j0])
        return True
    for p, q in zip(main_live, main_live[1:]):
        if abs(p["t0"] + p["d"] - q["t0"]) > 1.5 / fps or p["base"] == q["base"]: continue   # a gap, or a jump cut inside one take
        if not (a.bridge or flag(q["seg"], "bridge")): continue
        lead = min(N["bridgeLead"], p["d"] / 2); tail = min(N["bridgeTail"], q["d"] / 2)
        rt = lambda it: 1.0 if it["speed"] >= N["ambRealtimeSpeed"] else it["speed"]
        ok_l = bridge(p, p["s0"] + p["d"] * rt(p), tail, q["t0"], up=False)
        ok_j = bridge(q, q["s0"] - lead * rt(q), lead, q["t0"] - lead, up=True)
        nbr += ok_l or ok_j

    # ---- 3. room tone in the holes (between the first and the last word of the dialogue)
    w = np.clip(cover, 0, 1); live = np.flatnonzero(w > 0.5)
    fills = 0
    if len(live):
        first, last = live[0], live[-1]; hole = (w < 0.999); hole[:first] = False; hole[last:] = False
        idx = np.flatnonzero(np.diff(np.concatenate([[0], hole.astype(np.int8), [0]])))
        runs = list(zip(idx[::2], idx[1::2])); tones = {}
        main_items = sorted([it for it in items if it["kind"] != "mute" and not it["vo"]], key=lambda it: it["t0"])
        for r0, r1 in runs:
            t = r0 / SR; prev = [it for it in main_items if it["t0"] <= t] or main_items
            it = prev[-1]; b = it["base"]
            if b not in tones:   # the room under this take: its quietest stretch near the used ranges
                rs = [x for x in items if x["base"] == b and x["kind"] == "speech"]
                pool = np.concatenate([src.get(x, x["s0"] - 2, x["s0"] + x["d"] * x["speed"] + 2) for x in rs]) if rs else np.zeros(0)
                tones[b] = V.quiet_stretch(pool * 10 ** (gain.get(b, 0) / 20))
            seg = tones[b]
            if seg is None: continue
            # (1 − w) follows the neighbours' own fades, so the room comes in exactly as the voice goes out
            put(r0, r1, V.loop_fill(seg, r1 - r0) * (1 - w[r0:r1])); fills += 1
    raw = (rawpre if rawpre is not None else stem).copy() if a.keep_raw else None

    # ---- 4. the one chain
    stem, chain = V.voice_chain(stem, tune=tune)

    # ---- 5. bleeps
    nb = 0
    if bleeps:
        peak = N["bleepGain"] - (N["targetLufs"] - N["stemLufs"])
        R = int(0.01 * SR); m = np.ones(L); tones = []
        for bl in bleeps:
            s0 = max(0.0, bl["startMs"] / 1000 - 0.04); s1 = bl["endMs"] / 1000 + 0.04
            i0, i1 = int(s0 * SR), min(L, int(s1 * SR))
            if i1 <= i0: continue
            m[i0:i1] = 0
            m[max(0, i0 - R): i0] = np.minimum(m[max(0, i0 - R): i0], np.linspace(1, 0, i0 - max(0, i0 - R)))
            m[i1: min(L, i1 + R)] = np.minimum(m[i1: min(L, i1 + R)], np.linspace(0, 1, min(L, i1 + R) - i1))
            tones.append((i0, V.bleep_tone(s1 - s0, peak))); nb += 1
        stem *= m
        for i0, tone in tones: stem[i0: i0 + len(tone)] += tone[: L - i0]

    V.write(a.out, stem, subtype="PCM_24")
    if raw is not None: V.write("work/voice/dialogue_raw.wav", raw); print("A/B: work/voice/dialogue_raw.wav (assembly only) vs", a.out)
    if os.path.isdir("reel/src"): open(ts_path, "w").write(TS.format(val=json.dumps(os.path.relpath(a.out, "reel/public"))))
    rep = {"sig": sig, "out": a.out, "seconds": round(L / SR, 2), "segments": sum(it["kind"] != "mute" for it in items),
           "voiceovers": sorted({it["path"] for it in items if it["vo"]}), "cuts": cuts, "roomToneFills": fills, "bleeps": nb, "bridges": nbr,
           "takeGainsDb": {k: round(v, 1) for k, v in gain.items()}, "chain": chain}
    if tune: rep["tune"] = tune; rep["leveler"] = levrep
    V.save_json(rep, rep_p)
    o = chain["out"]; eq = chain.get("eq", {})
    print(f"{rep['segments']} segments, {len(cuts)} crossfaded cuts, {fills} room-tone fills, {nb} bleeps, {nbr} J/L bridges; take gains {rep['takeGainsDb']}")
    print(f"EQ {eq}; compressor over threshold {chain['comp']['overPct']}% (max {chain['comp']['maxGrDb']} dB); "
          f"de-esser {chain.get('deess', {}).get('activePct', 0)}% (max {chain.get('deess', {}).get('maxDb', 0)} dB); limiter {chain['limit']['limitedPct']}%")
    if tune:
        print(f"voice_tune: {sorted(tune)}; leveler {levrep}; expander {chain.get('expander')}; resonances {chain.get('resonances')}; "
              f"notches {chain.get('notches') or '—'}; extraEq {chain.get('extraEq') or '—'}")
    print(f"stem {o['lufs']} LUFS, LRA {o['lra']} LU, true peak {o['truePeak']} dBTP")
    print("DIALOGUE_DONE", a.out)


